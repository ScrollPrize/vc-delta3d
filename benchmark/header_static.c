/* Cross-validated fixed header distributions. Reuses the actual schema and
 * eight-lane rANS implementation; no independent entropy-code approximation. */
#include "ng/header.c"
#include "rans.h"
#include <stdio.h>
#define CHECK(x) do{if(!(x)){fprintf(stderr,"check failed %d: %s\n",__LINE__,#x);exit(1);}}while(0)
typedef struct {uint8_t *labels[2];size_t n,base,overhead,table;unsigned profile,predictor,fold,channel; } sample;
static unsigned varbytes(size_t n){unsigned b=1;while(n>=128){n>>=7;b++;}return b;}
static unsigned key(const sample*s,unsigned mode){return mode==0?0:mode==1?s->profile:mode==2?s->predictor:s->profile*13+s->predictor;}
static sample read_sample(const char *path,unsigned profile,unsigned predictor,unsigned fold){
    sample s={0};s.profile=profile;s.predictor=predictor;s.fold=fold;
    FILE*f=fopen(path,"rb");CHECK(f&&!fseek(f,0,SEEK_END));long size=ftell(f);CHECK(size>0);rewind(f);
    uint8_t*p=malloc(size);CHECK(p&&fread(p,1,size,f)==(size_t)size);fclose(f);s.base=size;
    arrays a={0};walk w={{p,size,0,1},{0},&a,1,0};CHECK(schema(&w,1));
    size_t lengths[134];for(unsigned k=0;k<a.count;k++){lengths[k]=varget(&w.input);s.n+=lengths[k];}
    unsigned tag=get(&w.input,1);size_t zn=varget(&w.input);const uint8_t*z=take(&w.input,zn);CHECK(w.input.ok);
    s.overhead=size-zn-varbytes(zn); /* includes unchanged one-byte mode */
    s.labels[0]=malloc(s.n?s.n:1);s.labels[1]=malloc(s.n?s.n:1);CHECK(s.labels[0]&&s.labels[1]);
    if(tag&1){uint16_t freq[256];CHECK(!ng_read_freq_table(z,zn,freq,&s.table));CHECK(vc_ng_stream_decode(z,zn,s.labels[0],s.n));}
    else{CHECK(zn==s.n);memcpy(s.labels[0],z,s.n);}
    size_t at=0;if(tag&2)for(unsigned k=0;k<a.count;k++){delta(s.labels[0]+at,lengths[k],1);at+=lengths[k];}
    memcpy(s.labels[1],s.labels[0],s.n);at=0;
    for(unsigned k=0;k<a.count;k++){delta(s.labels[1]+at,lengths[k],0);at+=lengths[k];}
    free(p);free(a.words.data);free(w.output.data);return s;
}
int main(int argc,char**argv){
    CHECK(argc==2||argc==3);FILE*f=fopen(argv[1],"r");CHECK(f);sample samples[4096];unsigned ns=0,p,c,fold,channel;char path[4096];
    while(fscanf(f,"%4095s %u %u %u %u",path,&p,&c,&fold,&channel)==5){CHECK(ns<4096&&p<4&&c<13&&fold<2&&channel<18);samples[ns]=read_sample(path,p,c,fold);samples[ns++].channel=channel;}fclose(f);
    if(argc==3){
        CHECK(!strcmp(argv[2],"--tables"));
        puts("/* Global header label distributions, trained on 576 frozen headers.\n * Generated by benchmark/header_static.c --tables; sum=4096, all symbols covered. */\nstatic const uint16_t header_freq[2][256] = {");
        for(unsigned d=0;d<2;d++){
            uint64_t hist[256],total=256;uint32_t freq[256];for(unsigned v=0;v<256;v++)hist[v]=1;
            for(unsigned i=0;i<ns;i++)for(size_t j=0;j<samples[i].n;j++){hist[samples[i].labels[d][j]]++;total++;}
            vc_rans_normalize(hist,total,freq);puts("    {");
            for(unsigned v=0;v<256;v++){printf("%s%u,%s",v%16==0?"        ":"",freq[v],v%16==15?"\n":" ");}
            puts("    },");
        }puts("};");return 0;
    }
    for(unsigned test=0;test<20;test++)for(unsigned mode=0;mode<4;mode++){
        uint64_t hist[52][2][256]={0},global[2][256]={0};uint32_t freq[52][2][256];unsigned trained[52]={0};
        for(unsigned i=0;i<ns;i++)if(test<2?samples[i].fold!=test:samples[i].channel!=test-2){sample*s=&samples[i];unsigned g=key(s,mode);trained[g]++;
            for(unsigned d=0;d<2;d++)for(size_t j=0;j<s->n;j++){hist[g][d][s->labels[d][j]]++;global[d][s->labels[d][j]]++;}}
        for(unsigned g=0;g<52;g++)for(unsigned d=0;d<2;d++){
            uint64_t h[256],total=0;for(unsigned v=0;v<256;v++){h[v]=(trained[g]?hist[g][d][v]:global[d][v])+1;total+=h[v];}
            vc_rans_normalize(h,total,freq[g][d]);
        }
        for(unsigned i=0;i<ns;i++)if(test<2?samples[i].fold==test:samples[i].channel==test-2){sample*s=&samples[i];unsigned g=key(s,mode);
            size_t best=s->overhead+varbytes(s->n)+s->n; /* unchanged raw option */
            for(unsigned d=0;d<2;d++)if(s->n){uint8_t*encoded=NULL;size_t en=0;
                CHECK(vc_rans_encode_frequencies(s->labels[d],s->n,0,freq[g][d],&encoded,&en));
                uint8_t*decoded=malloc(s->n);CHECK(decoded&&vc_rans_decode(encoded,en,decoded,s->n)&&!memcmp(decoded,s->labels[d],s->n));
                size_t payload=en-512,bytes=s->overhead+varbytes(payload)+payload+(mode!=0);
                if(bytes<best)best=bytes;free(decoded);free(encoded);
            }
            printf("{\"index\":%u,\"fold\":%u,\"mode\":%u,\"baseline\":%zu,\"table\":%zu,\"fixed\":%zu,\"hybrid\":%zu}\n",i,test,mode,s->base,s->table,best,best<s->base?best:s->base);
        }
    }
    for(unsigned i=0;i<ns;i++){free(samples[i].labels[0]);free(samples[i].labels[1]);}return 0;
}
